/**
 * Generates the Chrome Web Store listing for each extension.
 *
 * Everything the submission form asks for, in the order it asks for it, so
 * publishing is copy and paste rather than a writing exercise. The permission
 * justifications matter most: a submission that leaves them vague is the usual
 * reason a first review comes back rejected.
 *
 * Usage: node tools/make-listings.mjs
 */

import { writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { EXTENSIONS } from './extensions.mjs';
import { CONTENT } from './content.mjs';
import { LISTINGS, CATEGORIES } from './listings.mjs';
import { FEATURES, PRO_BY_DEFAULT } from '../shared/entitlements.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const LABELS = {
  'export-json': 'Export as JSON',
  'export-csv': 'Export as CSV',
  'export-md': 'Export as Markdown',
  'social-preview': 'Social sharing preview',
  'tag-ids': 'Tag identifier extraction',
  audit: 'Storefront audit',
  variants: 'Variant table',
  'raw-tree': 'Raw data tree',
  refresh: 'Live refresh',
  uncapped: 'Uncapped copy and export',
  'front-matter': 'YAML front matter',
  delimiter: 'Delimiter choice',
  evidence: 'Detection evidence',
  versions: 'Library versions',
};

/** Markdown is not allowed in the store's detailed description; it is plain text. */
function plain(text) {
  return String(text)
    .replace(/\*\*/g, '')
    .replace(/`/g, '"')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
}

function listingFor(extension) {
  const listing = LISTINGS[extension.slug];
  const content = CONTENT[extension.slug];
  const features = FEATURES[extension.slug];
  if (!listing || !content) throw new Error('No listing content for ' + extension.slug);

  if (listing.storeName.length > 75) {
    throw new Error(extension.slug + ': store name is ' + listing.storeName.length + ' chars (max 75)');
  }
  if (extension.description.length > 132) {
    throw new Error(extension.slug + ': short description is too long');
  }

  const out = [];
  const push = (...lines) => out.push(...lines);

  push('# Chrome Web Store listing - ' + extension.name);
  push('');
  push('Generated by tools/make-listings.mjs. Paste each block into the field it names.');
  push('');
  push('---');
  push('');

  // --- Identity ---
  push('## 1. Name');
  push('');
  push('> ' + listing.storeName);
  push('');
  push('`' + listing.storeName.length + '/75 characters.` The phrase after the dash is what the');
  push("store's search matches on. Do not turn it into a keyword list - that gets rejected.");
  push('');

  push('## 2. Short description');
  push('');
  push('> ' + extension.description);
  push('');
  push('`' + extension.description.length + '/132 characters.`');
  push('');

  push('## 3. Category');
  push('');
  push('> ' + CATEGORIES[extension.slug]);
  push('');

  push('## 4. Language');
  push('');
  push('> English (United States)');
  push('');
  push('---');
  push('');

  // --- Detailed description ---
  push('## 5. Detailed description');
  push('');
  push('Plain text, no Markdown - the store renders it literally. Copy from the line');
  push('below the rule to the one above the next rule.');
  push('');
  push('---');
  push('');
  push(plain(listing.hook));
  push('');
  push(plain(extension.tagline));
  push('');
  push('WHAT IT DOES');
  push('');
  for (const feature of content.features) push('• ' + plain(feature));
  push('');
  push(plain(content.outputs));
  push('');
  push('PRIVACY');
  push('');
  push('This extension collects nothing. No account, no sign-up, no analytics, no');
  push('telemetry, no servers. It reads the page you explicitly ask it to inspect,');
  push("keeps the result in the popup's memory, and forgets it when you close the");
  push('popup. Nothing is written to disk unless you click an export button, and');
  push('nothing is ever transmitted anywhere.');
  push('');
  push('PERMISSIONS');
  push('');
  push('• activeTab - gives access to the current tab only at the moment you click the');
  push('  icon, and only until you navigate away. This is why the extension needs no');
  push('  access to your browsing history and no permission to run on every site.');
  push('• scripting - required to read the page once you have clicked the icon.');
  push(
    PRO_BY_DEFAULT
      ? '• storage - keeps a single first-run timestamp on your own device. Nothing else.'
      : '• storage - holds a licence key on your own device. Nothing else is stored.'
  );
  push('');
  push('That is the complete list. There is no background process and no host');
  push('permissions.');
  push('');
  if (PRO_BY_DEFAULT) {
    push('EVERYTHING IS INCLUDED');
    push('');
    push('No account, no sign-up, no trial, no paid tier. Every feature works the');
    push('moment you install it, including: ' +
      features.pro.map((f) => LABELS[f] || f).join(', ') + '.');
    push('');
    push('The source is open: github.com/swanca/chrome-inspector-suite');
  } else {
    push('FREE AND PRO');
    push('');
    push('Inspection is free and stays free.');
    push('');
    push('Pro adds: ' + features.pro.map((f) => LABELS[f] || f).join(', ') + '.');
  }
  push('');
  push('PAGES IT CANNOT READ');
  push('');
  push('Chrome forbids extensions on its own pages - chrome://, the Web Store, and');
  push('view-source. The extension says which case you have hit rather than failing');
  push('silently. Local files work if you enable "Allow access to file URLs" on its');
  push('details page.');
  push('');
  push('---');
  push('');

  // --- Screenshots ---
  push('## 6. Screenshots');
  push('');
  push('At least one is required. 1280x800 or 640x400, PNG or JPEG. These are the');
  push('single biggest factor in whether someone installs, so shoot all five.');
  push('');
  listing.shots.forEach((shot, index) => push((index + 1) + '. ' + shot));
  push('');
  push('Shoot at 1280x800: set Chrome to that window size, open the popup, and');
  push('capture the popup together with enough of the page behind it to show the');
  push('context. A popup alone on white looks like a screenshot of nothing.');
  push('');
  push('---');
  push('');

  // --- Privacy tab ---
  push('## 7. Privacy practices tab');
  push('');
  push('The tab that most often sends a submission back. Every answer here is "no".');
  push('');
  push('**Single purpose**');
  push('');
  push('> ' + listing.singlePurpose);
  push('');
  push('**Permission justifications**');
  push('');
  push('| Permission | Paste this |');
  push('|---|---|');
  push(
    '| `activeTab` | The extension reads the page the user is on, but only after they click its toolbar icon. activeTab grants that access for that one tab and only until navigation, which avoids requesting host permissions for every site. |'
  );
  push(
    '| `scripting` | Used to run a single read-only collector function in the page once the user has clicked the icon. It reads the DOM and returns data to the popup. It never modifies the page. |'
  );
  push(
    '| `storage` | Stores a licence key on the user\'s own device so the paid tier does not require an account or a server. Nothing else is stored and nothing is transmitted. |'
  );
  push('');
  push('**Remote code**');
  push('');
  push('> No. All code is included in the package. Nothing is fetched or evaluated at runtime.');
  push('');
  push('**Data usage** - tick nothing. Then declare:');
  push('');
  push('- [x] I do not sell or transfer user data to third parties, outside of the approved use cases');
  push('- [x] I do not use or transfer user data for purposes that are unrelated to my item\'s single purpose');
  push('- [x] I do not use or transfer user data to determine creditworthiness or for lending purposes');
  push('');
  push('---');
  push('');

  // --- Search ---
  push('## 8. Searches this listing targets');
  push('');
  push('Not to be stuffed anywhere. They are what the name and the description were');
  push('written to answer.');
  push('');
  for (const query of listing.queries) push('- ' + query);
  push('');
  push('---');
  push('');

  // --- Packaging ---
  push('## 9. Package to upload');
  push('');
  push('```bash');
  push('cd extensions/' + extension.slug);
  push('zip -r ../../' + extension.slug + '.zip manifest.json icons src');
  push('```');
  push('');
  push('Ship only those three. `test/`, `README.md` and this file are development');
  push('artefacts and only slow the review down.');
  push('');
  push('---');
  push('');
  push('## 10. Before you press submit');
  push('');
  push('- [ ] Version bumped in `tools/extensions.mjs`, then `node tools/scaffold.mjs`');
  push('- [ ] `npm test` and `npm run check` both green');
  push('- [ ] Loaded unpacked once and the popup actually opened');
  push('- [ ] Five screenshots taken at 1280x800');
  push('- [ ] Privacy tab filled in exactly as above');
  push('- [ ] A support email you will read set on the account');

  return out.join('\n') + '\n';
}

let written = 0;
for (const extension of EXTENSIONS) {
  const dir = join(ROOT, 'extensions', extension.slug);
  if (!existsSync(dir)) continue;

  writeFileSync(join(dir, 'STORE-LISTING.md'), listingFor(extension));
  written++;
}

console.log('Wrote ' + written + ' store listings.');
